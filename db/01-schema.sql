-- testVue 스키마 (/app/testApp db/schema.sql에서 화면에 쓰는 테이블만 가져왔다)
-- 테이블 이름은 SQL 매퍼와 같게 대문자로 만든다 (Linux MySQL은 테이블 이름 대소문자를 가린다).
--   mysql -h127.0.0.1 -utvueapp -p testVue < db/01-schema.sql

DROP TABLE IF EXISTS TBTS_SAMPLE_BOARD;
DROP TABLE IF EXISTS TBSY_RESOURCE;
DROP TABLE IF EXISTS TBCM_COMMON_CODE;
DROP TABLE IF EXISTS TBCM_COMMON_CODE_GROUP;
DROP TABLE IF EXISTS TBSY_LOGIN_HIST;
DROP TABLE IF EXISTS TBSY_LOGIN;
DROP TABLE IF EXISTS TBIN_EMPMST;
DROP TABLE IF EXISTS TBSY_MEMBER;

-- [SY] 회원사(회사) 마스터
CREATE TABLE TBSY_MEMBER (
    MB_ID         VARCHAR(20)  NOT NULL COMMENT '회원사ID',
    MB_NM         VARCHAR(100) NULL     COMMENT '회원사명',
    REPRESENT_NM  VARCHAR(30)  NULL     COMMENT '대표자',
    TELNO         VARCHAR(14)  NULL     COMMENT '전화번호',
    CONT_FRYMD    VARCHAR(10)  NULL     COMMENT '계약시작일(yyyyMMdd)',
    CONT_TOYMD    VARCHAR(10)  NULL     COMMENT '계약종료일(yyyyMMdd)',
    USE_YN        VARCHAR(1)   NULL DEFAULT 'Y' COMMENT '사용여부',
    SORT_NO       INT          NULL DEFAULT 0   COMMENT '정렬순서',
    MEMO          VARCHAR(200) NULL     COMMENT '메모',
    IN_EMP_CD     VARCHAR(20)  NULL,
    IN_DTM        DATETIME     NULL,
    UP_EMP_CD     VARCHAR(20)  NULL,
    UP_DTM        DATETIME     NULL,
    PRIMARY KEY (MB_ID)
) COMMENT '회원사';

-- [IN] 인사 마스터(직원)
CREATE TABLE TBIN_EMPMST (
    MB_ID    VARCHAR(20)  NOT NULL,
    EMP_CD   VARCHAR(20)  NOT NULL COMMENT '사원코드',
    EMP_NM   VARCHAR(50)  NULL     COMMENT '사원명',
    EMAIL    VARCHAR(100) NULL,
    PRIMARY KEY (MB_ID, EMP_CD)
) COMMENT '직원';

-- [SY] 로그인 계정 (USER_PWD = SHA-256 16진수)
CREATE TABLE TBSY_LOGIN (
    MB_ID           VARCHAR(20)  NOT NULL,
    EMP_CD          VARCHAR(20)  NOT NULL,
    LOGIN_ID        VARCHAR(20)  NOT NULL COMMENT '로그인ID',
    USER_PWD        VARCHAR(128) NULL     COMMENT '비밀번호(SHA-256)',
    ACCT_LOCK_TYPE  VARCHAR(1)   NULL DEFAULT 'N' COMMENT '계정잠금여부',
    IN_EMP_CD       VARCHAR(20)  NULL,
    IN_DTM          DATETIME     NULL,
    PRIMARY KEY (MB_ID, EMP_CD),
    UNIQUE KEY UK_TBSY_LOGIN_LOGIN_ID (LOGIN_ID)
) COMMENT '로그인 계정';

-- [SY] 로그인 이력
CREATE TABLE TBSY_LOGIN_HIST (
    SEQ        BIGINT       NOT NULL AUTO_INCREMENT,
    MB_ID      VARCHAR(20)  NULL,
    EMP_CD     VARCHAR(20)  NULL,
    LOGIN_IP   VARCHAR(40)  NULL,
    LOGIN_DTM  DATETIME     NULL,
    PRIMARY KEY (SEQ),
    KEY IX_TBSY_LOGIN_HIST_01 (MB_ID, LOGIN_DTM)
) COMMENT '로그인 이력';

-- [CM] 공통코드그룹
CREATE TABLE TBCM_COMMON_CODE_GROUP (
    MB_ID            VARCHAR(20)  NOT NULL,
    GRP_CMM_CD       VARCHAR(100) NOT NULL COMMENT '그룹코드',
    GRP_CMM_CD_NM    VARCHAR(150) NULL     COMMENT '그룹코드명',
    GRP_CMM_CD_DESC  VARCHAR(300) NULL     COMMENT '설명',
    SYSTEM_GUBUN     VARCHAR(10)  NULL     COMMENT '시스템구분',
    SORT_NO          BIGINT       NULL DEFAULT 0,
    IN_EMP_CD        VARCHAR(20)  NULL,
    IN_DTM           DATETIME     NULL,
    UP_EMP_CD        VARCHAR(20)  NULL,
    UP_DTM           DATETIME     NULL,
    PRIMARY KEY (MB_ID, GRP_CMM_CD)
) COMMENT '공통코드그룹';

-- [CM] 공통코드
CREATE TABLE TBCM_COMMON_CODE (
    MB_ID       VARCHAR(20)  NOT NULL,
    GRP_CMM_CD  VARCHAR(100) NOT NULL,
    CD_VL       VARCHAR(100) NOT NULL COMMENT '코드값',
    CD_VL_NM    VARCHAR(150) NULL     COMMENT '코드명',
    USE_YN      VARCHAR(2)   NULL DEFAULT 'Y',
    SORT_NO     BIGINT       NULL DEFAULT 0,
    IN_EMP_CD   VARCHAR(20)  NULL,
    IN_DTM      DATETIME     NULL,
    UP_EMP_CD   VARCHAR(20)  NULL,
    UP_DTM      DATETIME     NULL,
    PRIMARY KEY (MB_ID, GRP_CMM_CD, CD_VL)
) COMMENT '공통코드';

-- [SY] 메뉴. PRNT_RESOURCE_ID가 NULL이면 상위 메뉴, RESOURCE_URL은 화면 경로(vue-router path)
CREATE TABLE TBSY_RESOURCE (
    MB_ID             VARCHAR(20)  NOT NULL,
    RESOURCE_ID       VARCHAR(20)  NOT NULL,
    PRNT_RESOURCE_ID  VARCHAR(20)  NULL,
    RESOURCE_NAME     VARCHAR(100) NOT NULL,
    RESOURCE_URL      VARCHAR(200) NULL DEFAULT 'NONE',
    SORT_NO           INT          NOT NULL DEFAULT 0,
    USE_YN            VARCHAR(1)   NOT NULL DEFAULT 'Y',
    IN_EMP_CD         VARCHAR(20)  NULL,
    IN_DTM            DATETIME     NULL,
    PRIMARY KEY (MB_ID, RESOURCE_ID)
) COMMENT '메뉴';

-- [TS] 샘플게시판 (삭제는 USE_YN='N')
CREATE TABLE TBTS_SAMPLE_BOARD (
    SEQ        BIGINT        NOT NULL AUTO_INCREMENT,
    MB_ID      VARCHAR(20)   NOT NULL,
    TITLE      VARCHAR(200)  NOT NULL COMMENT '제목',
    CONTENT    VARCHAR(4000) NULL     COMMENT '내용',
    WRITER_NM  VARCHAR(50)   NULL     COMMENT '작성자',
    USE_YN     VARCHAR(1)    NOT NULL DEFAULT 'Y',
    IN_EMP_CD  VARCHAR(20)   NULL,
    IN_DTM     DATETIME      NULL,
    UP_EMP_CD  VARCHAR(20)   NULL,
    UP_DTM     DATETIME      NULL,
    PRIMARY KEY (SEQ)
) COMMENT '샘플게시판';
